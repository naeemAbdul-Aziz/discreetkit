RETURNS TRIGGER AS $$
DECLARE
    avg_minutes integer;
BEGIN
    IF NEW.pharmacy_id IS NOT NULL AND (OLD.pharmacy_id IS NULL OR OLD.pharmacy_id != NEW.pharmacy_id) THEN
        SELECT (estimated_min_minutes + estimated_max_minutes) / 2 INTO avg_minutes
        FROM public.pharmacy_service_areas
        WHERE pharmacy_id = NEW.pharmacy_id AND area_name ILIKE '%' || NEW.delivery_area || '%' AND is_active = true
        LIMIT 1;
        
        NEW.estimated_delivery_time := now() + (COALESCE(avg_minutes, 60) || ' minutes')::interval;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_set_estimated_delivery_time ON public.orders;
