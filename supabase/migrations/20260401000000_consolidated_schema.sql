CREATE OR REPLACE VIEW public.pharmacy_payouts_due AS
SELECT 
    p.id as pharmacy_id,
    p.name as pharmacy_name,
    p.partner_code,
    p.trade_discount_percentage,
    COUNT(o.id) as total_orders,
    SUM(o.total_price_ghs) as total_revenue,
    SUM(o.total_price_ghs * (1 - (COALESCE(p.trade_discount_percentage, 20) / 100))) as payout_due,
    MIN(o.created_at) as period_start,
    MAX(o.created_at) as period_end
FROM public.orders o
JOIN public.pharmacies p ON o.pharmacy_id = p.id
WHERE o.status = 'completed'
GROUP BY p.id, p.name, p.partner_code, p.trade_discount_percentage;

CREATE OR REPLACE VIEW public.active_refill_subscriptions AS
SELECT 
  mrs.id, mrs.subscription_code, mrs.user_id, mrs.product_id, p.name as product_name,
  p.price_ghs, p.image_url, mrs.status, mrs.frequency, mrs.next_delivery_date,
  mrs.prescription_verified, mrs.prescription_expiry_date, mrs.enrolled_at,
  ph.name as pharmacy_name, ph.id as pharmacy_id
FROM public.medication_refill_subscriptions mrs
JOIN public.products p ON mrs.product_id = p.id
LEFT JOIN public.pharmacies ph ON mrs.pharmacy_id = ph.id
WHERE mrs.status = 'active';

