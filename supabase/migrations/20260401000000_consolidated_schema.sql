CREATE OR REPLACE FUNCTION generate_partner_code() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.partner_code IS NULL THEN
        NEW.partner_code := 'DK-PARTNER-' || LPAD(floor(random()*1000)::text, 3, '0') || upper(substring(md5(random()::text) from 1 for 3));
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_set_partner_code BEFORE INSERT ON public.pharmacies FOR EACH ROW EXECUTE FUNCTION generate_partner_code();

