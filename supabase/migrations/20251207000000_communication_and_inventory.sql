-- 1. ORDER MESSAGES (Communication System)
-- ==========================================

CREATE TABLE public.order_messages (
    id bigint generated by default as identity primary key,
    order_id bigint references public.orders(id) on delete cascade not null,
    sender_type text not null check (sender_type in ('admin', 'pharmacy', 'system')),
    sender_id uuid references auth.users(id) on delete set null,
    message text not null,
    is_internal boolean default false, -- Internal notes not visible to pharmacy
    read_at timestamptz,
    created_at timestamptz not null default now()
);

COMMENT ON TABLE public.order_messages IS 'Communication thread for orders between admin, pharmacy, and system notifications.';
COMMENT ON COLUMN public.order_messages.is_internal IS 'If true, only visible to admins (internal notes).';

CREATE INDEX order_messages_order_idx ON public.order_messages(order_id);
CREATE INDEX order_messages_created_idx ON public.order_messages(created_at DESC);

-- ==========================================
-- 2. INVENTORY RESERVATIONS
-- ==========================================

CREATE TABLE public.inventory_reservations (
    id bigint generated by default as identity primary key,
    order_id bigint references public.orders(id) on delete cascade not null,
    pharmacy_id bigint references public.pharmacies(id) on delete cascade not null,
    product_id bigint references public.products(id) on delete cascade not null,
    quantity integer not null check (quantity > 0),
    reserved_at timestamptz not null default now(),
    released_at timestamptz,
    status text not null check (status in ('active', 'released', 'fulfilled')) default 'active',
    UNIQUE(order_id, product_id)
);

COMMENT ON TABLE public.inventory_reservations IS 'Tracks inventory reserved for orders. Auto-releases after timeout if not fulfilled.';
COMMENT ON COLUMN public.inventory_reservations.status IS 'active: reserved, released: timeout/cancelled, fulfilled: delivered';

CREATE INDEX inventory_reservations_order_idx ON public.inventory_reservations(order_id);
CREATE INDEX inventory_reservations_pharmacy_idx ON public.inventory_reservations(pharmacy_id);
CREATE INDEX inventory_reservations_status_idx ON public.inventory_reservations(status) WHERE status = 'active';

