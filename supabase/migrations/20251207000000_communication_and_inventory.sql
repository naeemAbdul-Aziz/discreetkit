-- Function to create inventory reservations when order is accepted
CREATE OR REPLACE FUNCTION create_inventory_reservations()
RETURNS TRIGGER AS $$
DECLARE
    item jsonb;
    items_array jsonb;
BEGIN
    -- Only create reservations when order moves to 'processing' status
    IF NEW.status = 'processing' AND (OLD.status IS NULL OR OLD.status != 'processing') AND NEW.pharmacy_id IS NOT NULL THEN
        
        -- Parse items
        items_array := NEW.items::jsonb;
        
        -- Loop through items and create reservations
        FOR item IN SELECT * FROM jsonb_array_elements(items_array)
        LOOP
            INSERT INTO public.inventory_reservations (
                order_id,
                pharmacy_id,
                product_id,
                quantity,
                status
            ) VALUES (
                NEW.id,
                NEW.pharmacy_id,
                (item->>'id')::bigint,
                COALESCE((item->>'quantity')::integer, 1),
                'active'
            )
            ON CONFLICT (order_id, product_id) DO NOTHING;
            
            -- Deduct from pharmacy stock
            UPDATE public.pharmacy_products
            SET stock_level = stock_level - COALESCE((item->>'quantity')::integer, 1)
            WHERE pharmacy_id = NEW.pharmacy_id
              AND product_id = (item->>'id')::bigint
              AND stock_level >= COALESCE((item->>'quantity')::integer, 1);
        END LOOP;
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

COMMENT ON FUNCTION create_inventory_reservations() IS 'Automatically creates inventory reservations and deducts stock when order is accepted.';

-- Trigger for inventory reservations
DROP TRIGGER IF EXISTS trigger_create_inventory_reservations ON public.orders;
CREATE TRIGGER trigger_create_inventory_reservations
    AFTER INSERT OR UPDATE OF status, pharmacy_id ON public.orders
    FOR EACH ROW
    EXECUTE FUNCTION create_inventory_reservations();

-- Function to release expired reservations
CREATE OR REPLACE FUNCTION release_expired_reservations()
RETURNS void AS $$
BEGIN
    -- Release reservations older than 2 hours that are still active
    UPDATE public.inventory_reservations
    SET status = 'released',
        released_at = now()
    WHERE status = 'active'
      AND reserved_at < now() - interval '2 hours'
      AND order_id IN (
          SELECT id FROM public.orders
          WHERE status NOT IN ('out_for_delivery', 'completed')
      );
    
    -- Return stock to pharmacy
    UPDATE public.pharmacy_products pp
    SET stock_level = stock_level + ir.quantity
    FROM public.inventory_reservations ir
    WHERE pp.pharmacy_id = ir.pharmacy_id
      AND pp.product_id = ir.product_id
      AND ir.status = 'released'
      AND ir.released_at >= now() - interval '5 minutes'; -- Only process recently released
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

COMMENT ON FUNCTION release_expired_reservations() IS 'Releases inventory reservations that have timed out and returns stock.';

-- Function to mark reservations as fulfilled when order completes
CREATE OR REPLACE FUNCTION fulfill_inventory_reservations()
RETURNS TRIGGER AS $$
BEGIN
    -- Mark reservations as fulfilled when order is completed
    IF NEW.status = 'completed' AND (OLD.status IS NULL OR OLD.status != 'completed') THEN
        UPDATE public.inventory_reservations
        SET status = 'fulfilled',
            released_at = now()
        WHERE order_id = NEW.id
          AND status = 'active';
          
        -- Set actual delivery time
        UPDATE public.orders
        SET actual_delivery_time = now()
        WHERE id = NEW.id
          AND actual_delivery_time IS NULL;
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

COMMENT ON FUNCTION fulfill_inventory_reservations() IS 'Marks inventory reservations as fulfilled when order is completed.';

-- Trigger for fulfilling reservations
DROP TRIGGER IF EXISTS trigger_fulfill_inventory_reservations ON public.orders;
CREATE TRIGGER trigger_fulfill_inventory_reservations
    AFTER UPDATE OF status ON public.orders
    FOR EACH ROW
    EXECUTE FUNCTION fulfill_inventory_reservations();

-- Function to calculate and set estimated delivery time
CREATE OR REPLACE FUNCTION set_estimated_delivery_time()
RETURNS TRIGGER AS $$
DECLARE
    avg_minutes integer;
BEGIN
    -- Calculate estimated delivery when order is assigned to pharmacy
    IF NEW.pharmacy_id IS NOT NULL AND (OLD.pharmacy_id IS NULL OR OLD.pharmacy_id != NEW.pharmacy_id) THEN
        -- Get average delivery time from service area
        SELECT (estimated_min_minutes + estimated_max_minutes) / 2
        INTO avg_minutes
        FROM public.pharmacy_service_areas
        WHERE pharmacy_id = NEW.pharmacy_id
          AND area_name ILIKE '%' || NEW.delivery_area || '%'
          AND is_active = true
        LIMIT 1;
        
        -- Set estimated time (default 60 minutes if no service area found)
        NEW.estimated_delivery_time := now() + (COALESCE(avg_minutes, 60) || ' minutes')::interval;
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION set_estimated_delivery_time() IS 'Calculates and sets estimated delivery time based on pharmacy service area.';

-- Trigger for estimated delivery time
DROP TRIGGER IF EXISTS trigger_set_estimated_delivery_time ON public.orders;
CREATE TRIGGER trigger_set_estimated_delivery_time
    BEFORE INSERT OR UPDATE OF pharmacy_id ON public.orders
    FOR EACH ROW
    EXECUTE FUNCTION set_estimated_delivery_time();

